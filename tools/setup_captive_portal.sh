#!/usr/bin/env bash
# Captive-portal setup on the Host (Fedora) for the KeyMod NCM link.
#
# Mimics a hotel/Starbucks captive portal: the target installs nothing.
# When the device is plugged in, the Host hands out DHCP, hijacks every
# DNS name to itself and answers the OS connectivity probe (Windows NCSI,
# macOS captive.apple.com, Android generate_204) with a 302 redirect to
# the file manager. The OS then pops up its own built-in sign-in window.
#
# Idempotent — safe to re-run. Requires root:
#   sudo tools/setup_captive_portal.sh enp0s21f0u1u2
set -euo pipefail

IFACE="${1:-enp0s21f0u1u2}"
HOST_IP="192.168.20.1"
TARGET_IP="192.168.20.2"
FILE_MANAGER_PORT="8080"
PORTAL_UNIT="keymod-portal.service"
DNSMASQ_CONF="/etc/dnsmasq.d/keymod-ncm.conf"
REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"

if [[ $EUID -ne 0 ]]; then
    echo "run with sudo" >&2
    exit 1
fi

echo "[1/6] Host address on $IFACE"
ip addr change "$HOST_IP/24" dev "$IFACE" 2>/dev/null || \
    ip addr add "$HOST_IP/24" dev "$IFACE"

echo "[2/6] Installing dnsmasq if missing"
if ! command -v dnsmasq >/dev/null; then
    dnf install -y dnsmasq
fi

echo "[3/6] Writing $DNSMASQ_CONF (DHCP + DNS hijack)"
TARGET_MAC="$(ip neigh show dev "$IFACE" | awk -v ip="$TARGET_IP" '$1==ip {print $5; exit}')"
mkdir -p /etc/dnsmasq.d
cat > "$DNSMASQ_CONF" <<EOF
# KeyMod NCM link: captive portal DHCP + DNS (generated by setup_captive_portal.sh)
interface=$IFACE
bind-dynamic
port=53
dhcp-range=$HOST_IP,192.168.20.200,12h
dhcp-option=option:router,$HOST_IP
dhcp-option=option:dns-server,$HOST_IP
# every DNS name resolves to the Host so the OS probe lands on our port 80
address=/#/$HOST_IP
# Windows legacy DNS check expects this exact answer
address=/dns.msftncsi.com/131.107.255.255
EOF
# pin the target's current address if its MAC is known
if [[ -n "${TARGET_MAC:-}" && "$TARGET_MAC" != "<incomplete>" ]]; then
    echo "dhcp-host=$TARGET_MAC,$TARGET_IP" >> "$DNSMASQ_CONF"
    echo "  reserved $TARGET_IP for $TARGET_MAC"
fi

echo "[4/6] Enabling dnsmasq + firewall"
systemctl enable --now dnsmasq >/dev/null 2>&1 || systemctl restart dnsmasq
firewall-cmd --zone=public --add-service=dhcp --add-service=dns --add-service=http 2>/dev/null \
    || firewall-cmd --add-service=dhcp --add-service=dns --add-service=http 2>/dev/null || true
firewall-cmd --zone=public --permanent --add-service=dhcp --add-service=dns --add-service=http 2>/dev/null || \
    firewall-cmd --permanent --add-service=dhcp --add-service=dns --add-service=http 2>/dev/null || true

echo "[5/6] Installing $PORTAL_UNIT (port 80 -> file manager redirect)"
cat > "/etc/systemd/system/$PORTAL_UNIT" <<EOF
[Unit]
Description=KeyMod captive portal redirect (port 80 -> file manager)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
ExecStart=/usr/sbin/python3 ${REPO_DIR}/tools/portal_redirect.py --bind 0.0.0.0 --port 80
ExecStartPost=/usr/sbin/ip addr change ${HOST_IP}/24 dev ${IFACE}
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable --now "$PORTAL_UNIT"

echo "[6/6] Self test"
sleep 1
systemctl is-active dnsmasq "$PORTAL_UNIT" | tr '\n' ' '; echo
curl -s -o /dev/null -w "portal port 80: HTTP %{http_code} -> %{redirect_url}\n" \
    "http://$HOST_IP/connecttest.txt"
echo "Done. On next plug-in the target OS should show its captive-portal popup."
